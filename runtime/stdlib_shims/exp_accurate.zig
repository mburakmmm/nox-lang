const std = @import("std");

const ln2: f128 = 0.6931471805599453094172321214581765680755001343602552;

pub fn expAccurate(x: f64) f64 {
    if (std.math.isNan(x)) return x;
    if (x > 709.782712893384) return std.math.inf(f64);
    if (x < -745.2) return 0.0;
    const xf: f128 = x;
    const k_f = @round(xf / ln2);
    const k: i32 = @intFromFloat(k_f);
    const r: f128 = xf - k_f * ln2;
    var p: f128 = 1.0;
    var n: u32 = 28;
    while (n >= 1) : (n -= 1) {
        p = 1.0 + p * r / @as(f128, @floatFromInt(n));
    }
    // p * 2^k: `f128` üs aralığında tam; tek yuvarlama `@floatCast`te.
    const scaled = std.math.scalbn(p, k);
    return @floatCast(scaled);
}

