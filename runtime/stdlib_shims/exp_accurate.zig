test "expAccurate: 632 girdide kesin (80 basamak) referansla BİT-bit eşit" {
    var bad: usize = 0;
    for (table) |row| {
        const x: f64 = @bitCast(row[0]);
        const want: u64 = row[1];
        const got: u64 = @bitCast(expAccurate(x));
        if (got != want) {
            bad += 1;
            std.debug.print("exp({x}) bits got=0x{X} want=0x{X}\n", .{ x, got, want });
        }
    }
    try std.testing.expectEqual(@as(usize, 0), bad);
}

test "expAccurate: özel değerler ve sınırlar" {
    try std.testing.expectEqual(@as(f64, 1.0), expAccurate(0.0));
    try std.testing.expectEqual(@as(u64, 0x4005BF0A8B145769), @as(u64, @bitCast(expAccurate(1.0)))); // 2.718281828459045
    try std.testing.expect(std.math.isNan(expAccurate(std.math.nan(f64))));
    try std.testing.expectEqual(std.math.inf(f64), expAccurate(std.math.inf(f64)));
    try std.testing.expectEqual(@as(f64, 0.0), expAccurate(-std.math.inf(f64)));
    try std.testing.expectEqual(std.math.inf(f64), expAccurate(710.0));
    try std.testing.expectEqual(@as(f64, 0.0), expAccurate(-746.0));
    try std.testing.expect(expAccurate(709.78) < std.math.inf(f64));
    try std.testing.expect(expAccurate(-745.0) > 0.0); // altnormal
}

test "expAccurate: libm ile en çok 1 ULP, çoğunlukla aynı (rastgele tarama)" {
    var prng = std.Random.DefaultPrng.init(0xE1);
    const rand = prng.random();
    var diff: usize = 0;
    for (0..20000) |_| {
        const x = (rand.float(f64) - 0.5) * 100.0;
        const a = expAccurate(x);
        const b = std.math.exp(x);
        const ua: i64 = @bitCast(a);
        const ub: i64 = @bitCast(b);
        try std.testing.expect(@abs(ua - ub) <= 1);
        if (ua != ub) diff += 1;
    }
    try std.testing.expect(diff < 2000); // std.math.exp ~%0.5 oranında doğru yuvarlamadan sapar
}
